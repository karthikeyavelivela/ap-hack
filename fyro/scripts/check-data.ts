import { generateAll } from '../src/mocks/recordsGen';
import { buildDerived, emergingForWeek } from '../src/mocks/derived';
import { evalSummary } from '../src/mocks/evalStats';
let t = Date.now();
const recs = generateAll();
console.log('gen', recs.length, Date.now() - t, 'ms');
t = Date.now();
const d = buildDerived(recs);
console.log('derived', d.incidents.length, 'incidents', Date.now() - t, 'ms');
console.log(d.incidents.slice(0, 5).map((i) => [i.id, i.storeId, i.issue, i.severity, i.count, i.channels.length, i.status].join(' ')));
t = Date.now();
const em = emergingForWeek(d, 41);
console.log('emerging', em.length, Date.now() - t, 'ms');
console.log(em.slice(0, 10).map((e) => [e.storeId, e.issue, e.score, e.firstFireDay, e.last3, e.p.toExponential(1), e.planted ?? ''].join(' ')));
t = Date.now();
const ev = evalSummary(d);
console.log('eval', Date.now() - t, 'ms');
console.log(ev.metrics, ev.precision, ev.leadTime.map((l) => [l.storeId, l.detectedDay, l.leadDays].join(':')));
console.log(ev.sweep.map((s) => [s.pThreshold, s.falseAlarmsPerWeek.toFixed(1), s.avgLeadDays.toFixed(1)].join(' ')));
for (const r of recs.slice(200, 206)) console.log(r.channel, r.lang, r.issue, r.severity, JSON.stringify(r.text));
